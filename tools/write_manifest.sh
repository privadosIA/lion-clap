#!/usr/bin/env bash
# Writes tests/fixtures/MANIFEST.md from the current fixtures. Usage: tools/write_manifest.sh [reproducibility-comparison-file]
# Without a comparison file the existing "Reproducibility" section is kept as it is.
set -euo pipefail
cd "$(dirname "${BASH_SOURCE[0]}")/.."
IMAGE="${CLAP_IMAGE:-mediaorquestator/clap:1}"
WEIGHTS="${CLAP_WEIGHTS:-$HOME/Proyectos/mediaOrquestator/models/music/clap}"
CKPT_OUT="${CLAP_CKPT_OUT:-$HOME/Proyectos/mediaOrquestator/models/music/clap-safetensors}"
FX=tests/fixtures
previous="$(sed -n "/^## Reproducibility/,\$p" "$FX/MANIFEST.md" 2>/dev/null || true)"
versions="$(tools/run_golden.sh noop 2>/dev/null)"
snapshot="$(basename "$(ls -d "$WEIGHTS"/hub/models--laion--clap-htsat-unfused/snapshots/* | tail -1)")"
{
  echo "# Fixtures manifest"
  echo
  echo "Generated by \`tools/write_manifest.sh\`; checked by \`tools/verify_manifest.sh\`. Do not edit by hand."
  echo
  echo "## Environment"
  echo
  echo "- image: \`$IMAGE\` (id \`$(docker image inspect --format '{{.Id}}' "$IMAGE")\`)"
  echo "- model: \`laion/clap-htsat-unfused\`, snapshot revision \`$snapshot\`"
  echo "$versions" | sed 's/^/- /'
  echo "- run: CPU, 1 thread, \`torch.use_deterministic_algorithms(True)\`, seed 1234, offline (\`--network none\`)"
  echo
  echo "## Decisions the later changes rely on"
  echo
  echo "- Reference is the HF \`ClapFeatureExtractor\` (transformers), not laion_clap/torchlibrosa: no int16 quantisation."
  echo "- Mel filter bank used for \`input_features\`: **$(sed -n 's/.*"mel_bank_used": "\([a-z]*\)".*/\1/p' "$FX/frontend_cases.json")** (\`mel_filters_slaney\`); the HTK bank differs (see \`frontend_cases.json\`)."
  echo "- Waveforms are float32 at 48 kHz, at most 480000 samples; shorter ones are \`repeatpad\`-ed by the extractor. The noise case is cut from a 12 s source at a fixed offset (\`cut_offset\`); \`rand_trunc\` is never taken."
  echo "- \`audio_encoder_output\` / \`text_pooler_output\` are the pre-projection pooled outputs; \`*_projected\` are before L2 normalisation; \`*_embeddings\` are L2-normalised."
  echo "- \`logit_scale_a/t\` are the stored (log) values."
  echo
  echo "## Regenerate"
  echo
  echo '```bash'
  echo "tools/golden_all.sh        # = tools/run_golden.sh checkpoint; frontend; htsat; text; roberta; classify; similarity"
  echo "tools/write_manifest.sh"
  echo '```'
  echo
  echo "| file | produced by |"
  echo "|---|---|"
  echo "| \`model.safetensors\` (outside the repo, \`CLAP_CKPT_OUT\`) | \`tools/run_golden.sh checkpoint\` |"
  echo "| \`frontend.safetensors\`, \`frontend_cases.json\`, \`audio_embeddings.safetensors\` | \`tools/run_golden.sh frontend\` |"
  echo "| \`htsat_intermediates.safetensors\` | \`tools/run_golden.sh htsat\` |"
  echo "| \`roberta_intermediates.safetensors\` | \`tools/run_golden.sh roberta\` |"
  echo "| \`*.wav\`, \`classify_cases.json\`, \`classify_embeddings.safetensors\` | \`tools/run_golden.sh classify\` |"
  echo "| \`text_cases.json\`, \`text_embeddings.safetensors\` | \`tools/run_golden.sh text\` |"
  echo "| \`similarity.safetensors\` | \`tools/run_golden.sh similarity\` |"
  echo
  echo "## sha256"
  echo
  echo "| file | sha256 |"
  echo "|---|---|"
  (cd "$FX" && for f in $(ls | grep -v '^MANIFEST.md$' | LC_ALL=C sort); do echo "| \`$f\` | \`$(sha256sum "$f" | cut -d' ' -f1)\` |"; done)
  echo
  echo "Checkpoint (not in the repo): \`$(sha256sum "$CKPT_OUT/model.safetensors" | cut -d' ' -f1)  model.safetensors\`"
  if [[ $# -ge 1 ]]; then
    echo
    echo "## Reproducibility (two complete runs from a clean tests/fixtures/)"
    echo
    echo '```'
    cat "$1"
    echo '```'
  elif [[ -n "$previous" ]]; then
    echo
    echo "$previous"
  fi
} > "$FX/MANIFEST.md"
echo "wrote $FX/MANIFEST.md"
